def _require_halfvec_support() -> None:
    """Fail loudly if pgvector is too old for halfvec (needs >= 0.7.0)."""
    bind = op.get_bind()
    version = bind.execute(
        sa.text("SELECT extversion FROM pg_extension WHERE extname = 'vector'")
    ).scalar()
    if version is None:
        raise RuntimeError(
            "pgvector extension is not installed after CREATE EXTENSION — "
            "cannot create halfvec columns."
        )
    try:
        parts = tuple(int(p) for p in version.split(".")[:3])
        parts = parts + (0,) * (3 - len(parts))
    except ValueError:  # pragma: no cover - unexpected version string
        raise RuntimeError(
            f"Could not parse pgvector version '{version}'. halfvec requires "
            "pgvector >= 0.7.0."
        )
    if parts < (0, 7, 0):
        raise RuntimeError(
            f"pgvector {version} is installed, but this schema uses halfvec(3072), "
            "which requires pgvector >= 0.7.0. Upgrade the extension "
            "(e.g. `ALTER EXTENSION vector UPDATE;` on a build with 0.7+ available, "
            "or upgrade your Postgres/pgvector image) and re-run the migration."
        )


