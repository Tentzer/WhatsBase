def _create_rls() -> None:
    """Supabase RLS: tenant isolation for the frontend (anon key).

    The backend uses the service role and bypasses RLS entirely; these policies
    constrain the browser client so a logged-in owner only ever sees their own
    tenant's rows. Maps auth.uid() -> tenant_id via the users table.
    """
    op.execute(
        """
        CREATE OR REPLACE FUNCTION public.app_user_tenant_ids()
        RETURNS SETOF uuid
        LANGUAGE sql STABLE SECURITY DEFINER
        SET search_path = public
        AS $$
            SELECT tenant_id FROM public.users WHERE supabase_user_id = auth.uid();
        $$;
        """
    )

    # Enable RLS + tenant-isolation policy on exactly the tables in _RLS_POLICIES.
    for tbl, using in _RLS_POLICIES:
        op.execute(f"ALTER TABLE {tbl} ENABLE ROW LEVEL SECURITY")
        op.execute(f"CREATE POLICY tenant_isolation ON {tbl} USING ({using})")


