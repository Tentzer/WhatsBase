"""Conversation-agent guardrails -- code-side enforcement that mirrors the
per-tenant system prompt rules generated by the Builder (``builder/prompts.py``
``CONVERSATION_SYSTEM_TEMPLATE`` rules 1-6).

Per the skill invariant, guardrails live in BOTH places and must change
together: the prompt instructs the model, and these checks catch the cases it
slips through. Everything here is pure (no I/O, no LLM) so it is fully unit
testable without credentials.
"""

from __future__ import annotations

import re
from collections.abc import Iterable

# --------------------------------------------------------------------------- #
# Language mirroring (rule 4)
# --------------------------------------------------------------------------- #
_HEBREW_RE = re.compile(r"[֐-׿]")

# Emoji character classes -- strip_emojis() uses this as a mechanical backstop.
_EMOJI_RE = re.compile(
    "["
    "\U0001F000-\U0001FFFF"  # emoticons, misc symbols, pictographs, transport
    "\U00002600-\U000027FF"  # misc symbols (sun, heart, check mark, etc.)
    "\U00002B00-\U00002BFF"  # misc symbols and arrows (star, etc.)
    "\U0000FE00-\U0000FE0F"  # variation selectors (emoji modifiers)
    "\U0000200D"             # zero-width joiner (compound emoji)
    "]",
    re.UNICODE,
)


def detect_language(text: str) -> str:
    """Return ``"he"`` if the text contains Hebrew letters, else ``"en"``."""
    return "he" if _HEBREW_RE.search(text or "") else "en"


def language_directive(lang: str) -> str:
    if lang == "he":
        return "The customer wrote in Hebrew. Reply in Hebrew."
    return "The customer wrote in English. Reply in English."


# --------------------------------------------------------------------------- #
# Price/stock honesty (rules 2 & 3): never invent prices.
# Deliberately narrow -- only flag a number that sits next to a currency marker,
# so bare counts ("we have 3 sofas", "open until 18:00") are never blocked.
# --------------------------------------------------------------------------- #
_CURRENCY = r"(?:₪|ILS|NIS|shekels?|שקלים|שקל|ש\"ח)"
_NUM = r"\d{1,3}(?:[,\s]\d{3})+(?:\.\d+)?|\d+(?:\.\d+)?"
_AMOUNT_RE = re.compile(
    rf"{_CURRENCY}\s*({_NUM})|({_NUM})\s*{_CURRENCY}",
    re.IGNORECASE,
)


def _normalize_amount(raw: str) -> float | None:
    cleaned = raw.replace(",", "").replace(" ", "")
    try:
        return float(cleaned)
    except ValueError:
        return None


def extract_currency_amounts(text: str) -> list[float]:
    """Numbers in `text` that are adjacent to a currency marker."""
    out: list[float] = []
    for match in _AMOUNT_RE.finditer(text or ""):
        raw = match.group(1) or match.group(2)
        value = _normalize_amount(raw)
        if value is not None:
            out.append(value)
    return out


def any_price_mention(text: str) -> bool:
    """True when ``text`` contains any currency-adjacent number.

    Used for ``lead_qualification`` tenants where ALL price mentions are
    forbidden regardless of tool results.  Reuses ``extract_currency_amounts``
    so the detection logic stays in one place.
    """
    return bool(extract_currency_amounts(text))


def unsupported_price_claim(reply: str, allowed_prices: Iterable[float]) -> float | None:
    """First currency-adjacent amount in `reply` not backed by a tool-result
    price, or ``None`` when every such amount is supported (or there are none).
    """
    allowed = {round(float(p), 2) for p in allowed_prices if p is not None}
    for amount in extract_currency_amounts(reply):
        if round(amount, 2) not in allowed:
            return amount
    return None


# --------------------------------------------------------------------------- #
# Handoff triggers (rule 5): anger or an explicit request for a human.
# --------------------------------------------------------------------------- #
_HUMAN_RE = re.compile(
    r"\b(human|real person|speak to (?:someone|a person|an agent)|"
    r"talk to (?:someone|a person|an agent)|representative|manager|customer service)\b"
    r"|נציג(?:ה)?|אנושי|בן[ -]?אדם|לדבר עם מישהו|נציג שירות",
    re.IGNORECASE,
)
_ANGER_RE = re.compile(
    r"\b(angry|furious|useless|terrible|ridiculous|scam|fed up|stupid|worst|"
    r"unacceptable|disgrace)\b"
    r"|זבל|נורא|גרוע|מעצבן|נמאס|שערורי|לא מקובל",
    re.IGNORECASE,
)


def wants_human(text: str) -> bool:
    return bool(_HUMAN_RE.search(text or ""))


def is_angry(text: str) -> bool:
    return bool(_ANGER_RE.search(text or ""))


def should_handoff(text: str) -> bool:
    """True when the customer is angry or explicitly asks for a human (rule 5)."""
    return wants_human(text) or is_angry(text)


