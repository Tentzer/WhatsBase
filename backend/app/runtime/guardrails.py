def system_preamble(lang: str, now_str: str, agent_type: str = "catalog_sales") -> str:
    """Runtime guardrail + voice block appended to the tenant system prompt each turn.

    ``agent_type`` selects the guardrail block:
    - ``"lead_qualification"``: no-price + handoff-only rules.
    - anything else (default ``"catalog_sales"``): full catalog/price rules.
    """
    guardrail_block = (
        RUNTIME_GUARDRAILS_LEADQUAL
        if agent_type == "lead_qualification"
        else RUNTIME_GUARDRAILS
    )
    emoji_override = (
        "\n\nNo emojis -- never include any emoji character in a lead-qualification reply."
        if agent_type == "lead_qualification"
        else ""
    )
    return (
        f"{guardrail_block}\n\n{RUNTIME_VOICE}{emoji_override}\n\n"
        f"{language_directive(lang)}\nCurrent date and time: {now_str}."
    )


def fallback_reply(lang: str) -> str:
    """Graceful, language-mirrored reply for max-iteration / empty-response cases."""
    if lang == "he":
        return (
            "סליחה, לא הצלחתי"
            " להשלים את התשובה"
            " כרגע. אפשר לנסח"
            " מחדש, או שאחבר"
            " אותך לנציג אנושי?"
        )
    return (
        "Sorry, I couldn't complete that just now. Could you rephrase, "
        "or I can connect you with a human?"
    )


def strip_emojis(text: str) -> str:
    """Remove all emoji characters from *text*.

    Applied to lead_qualification replies as a mechanical backstop after the
    LLM call -- the system prompt already instructs no emojis; this ensures
    none slip through regardless.
    """
    return _EMOJI_RE.sub("", text)



def _format_price(price: float, currency: str | None) -> str:
    """₪3,990 for ILS, else '3,990 ILS'. Comma thousands; drop a .0 tail."""
    n = int(price) if float(price).is_integer() else price
    amount = f"{n:,}"
    cur = (currency or "").upper()
    return f"₪{amount}" if cur in ("ILS", "NIS") else f"{amount} {cur}".strip()


def cards_only_reply(lang: str, cards) -> str:
    """Neutral line when the agent sent product cards but no text of its own -- the
    turn succeeded, so don't fire the apologetic fallback after a card. Carries the
    card's name + price so the answer is never missing even on a silent turn."""
    parts = []
    for c in cards[:3]:
        name = ((c.name_he if lang == "he" else c.name_en) or c.name_en or c.name_he or "").strip()
        if name and c.price is not None:
            parts.append(f"{name} — {_format_price(c.price, c.currency)}")
        elif name:
            parts.append(name)
    listing = "; ".join(parts)
    if not listing:
        return (
            "הנה מה שמצאתי \U0001f642"
            " אפשר לעזור בעוד משהו?"
            if lang == "he"
            else "Here's what I found \U0001f642 Anything else I can help with?"
        )
    if lang == "he":
        return (
            f"{listing}. רוצה עוד פרטים?"
        )
    return f"{listing}. Want more details?"
